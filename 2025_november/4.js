const readline = require('readline');
const rl = readline.createInterface({
    input: process.stdin,
    output: process.stdout
});

let lines = 0;
let n = null;

const taskFn = (arrs) => {
    let minPrefix = 0;
    let maxPrefix = Math.pow(10, 10);

    arrs.forEach((el,) => {
        const [l, r, a] = el;
        minPrefix = Math.min(l, minPrefix + a);
        maxPrefix = Math.min(r, maxPrefix + a);
    })
}

let arr = [];

rl.on("line", (input) => {
    if (lines === 0) {
        n = +input;
        console.log(taskFn(input));
    } 
    if (lines > 0 && lines <= n+1){
        arr.push(input.split(' ').map(el => +el));
    }else {
        rl.close();
    }

    lines++;
});

